//! ============================================================================
//! I/O ペース制御の共通口。
//!
//! 通常実行は IdlePace（何もしない）を使う。
//! バックグラウンド実行だけが別実装を差し込み、本体ロジックと監視を分離する。
//! ============================================================================

use anyhow::Result;

// ============================================================================
// スナップショット／検証中に呼び出す待機フック。
// エラーは呼び出し側へそのまま伝播する（握りつぶさない）。
// ============================================================================
pub trait IoPace {
    // ===========================================================================
    // 1 エントリ（ファイルなど）の処理を始める前に呼ぶ。
    // ===========================================================================
    fn before_entry(&mut self) -> Result<()>;

    // ===========================================================================
    // 読み書きチャンクのたびに呼ぶ。bytes は今回処理したバイト数。
    // ===========================================================================
    fn after_chunk(&mut self, bytes: usize) -> Result<()>;
}

// ============================================================================
// 通常実行用。待機も監視もせず、常に成功を返す。
// ============================================================================
pub struct IdlePace;

impl IoPace for IdlePace {
    fn before_entry(&mut self) -> Result<()> {
        Ok(())
    }

    fn after_chunk(&mut self, _bytes: usize) -> Result<()> {
        Ok(())
    }
}
